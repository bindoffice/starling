#[tokio::test]
async fn exposes_request_metadata_and_limit_rate_variables() {
    let (prefix, config) = test_config(
        r#"
                worker_processes 1;
                events { worker_connections 64; }
                http {
                    limit_rate 2k;
                    limit_rate_after 512;
                    server {
                        listen 127.0.0.1:18131;
                        location / {
                            return 200 "$request_body|$request_length|$request_time\n";
                        }
                    }
                }
            "#,
        &[],
    );
    let http = config.http.as_ref().unwrap();
    let server = &http.servers[0];
    let request = Request {
        method: "POST".into(),
        target: "/".into(),
        version: "HTTP/1.1".into(),
        headers: (vec![Header {
            name: "Host".into(),
            value: "localhost".into(),
        }])
        .into(),
        body_stream: None,
        body: b"abc".to_vec(),
        remote_addr: "127.0.0.1:1234".into(),
        local_addr: "127.0.0.1:18131".into(),
        keep_alive: false,
    };
    let remote: SocketAddr = "127.0.0.1:1234".parse().unwrap();
    let local: SocketAddr = "127.0.0.1:18131".parse().unwrap();
    let variables = Variables::new(&request, "localhost", server, &local, &remote);
    let rate = response_rate(&server.context, &variables);
    assert_eq!(rate.rate, 2048);
    assert_eq!(rate.after, 512);
    assert_eq!(eval_variables("$request_body", &variables), "abc");
    assert_eq!(eval_variables("$request_length", &variables), "39");
    assert!(!eval_variables("$request_time", &variables).is_empty());

    let body = request_body(
        &config,
        "POST / HTTP/1.1\r\nHost: localhost\r\nContent-Length: 3\r\nConnection: close\r\n\r\nabc",
    )
    .await;
    let metadata = body.lines().last().unwrap_or_default();
    let fields: Vec<_> = metadata.split('|').collect();
    assert_eq!(fields[0], "abc");
    assert!(fields[1].parse::<u64>().is_ok_and(|length| length > 0));
    assert!(fields[2].parse::<f64>().is_ok_and(|time| time >= 0.0));
    let _ = std::fs::remove_dir_all(prefix);
}
