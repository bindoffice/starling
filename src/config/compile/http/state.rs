use super::*;

pub(super) struct HttpCompileState<'a> {
    pub(super) prefix: &'a Path,
    pub(super) context: EffectiveConfig,
    pub(super) mime_types: HashMap<String, String>,
    pub(super) default_type: String,
    pub(super) log_formats: HashMap<String, AccessLogFormat>,
    pub(super) upstreams: HashMap<String, UpstreamConfig>,
    pub(super) cache_paths: HashMap<String, Arc<ProxyCachePathConfig>>,
    pub(super) maps: HashMap<String, Arc<MapVariable>>,
    pub(super) geos: HashMap<String, Arc<GeoVariable>>,
    pub(super) split_clients: HashMap<String, Arc<SplitClientsVariable>>,
    pub(super) limit_req_zones: HashMap<String, Arc<LimitReqZone>>,
    pub(super) limit_conn_zones: HashMap<String, Arc<LimitConnZone>>,
    pub(super) charset_maps: Vec<CharsetMap>,
    pub(super) limit_req_directives: Vec<&'a Directive>,
    pub(super) limit_conn_directives: Vec<&'a Directive>,
    pub(super) server_directives: Vec<&'a Directive>,
    pub(super) seen_proxy_redirect: bool,
    pub(super) seen_proxy_cookie_domain: bool,
    pub(super) seen_proxy_cookie_path: bool,
    pub(super) seen_proxy_cookie_flags: bool,
    pub(super) seen_real_ip_from: bool,
    pub(super) seen_ssl_protocols: bool,
    pub(super) seen_proxy_ssl_protocols: bool,
    pub(super) seen_mirror: MirrorSeen,
    pub(super) seen_addition: AdditionSeen,
    pub(super) seen_ssi: SsiSeen,
    pub(super) seen_userid: UserIdSeen,
    pub(super) seen_secure_link: SecureLinkSeen,
    pub(super) seen_browser: BrowserSeen,
    pub(super) seen_expires: bool,
    pub(super) seen_if_modified_since: bool,
    pub(super) access_log_seen: bool,
    pub(super) seen_scope: SeenScopeDirectives,
}

impl HttpCompileState<'_> {
    pub(super) fn new(prefix: &Path) -> HttpCompileState<'_> {
        let mut context = EffectiveConfig::new(prefix);
        context.default_type = "text/plain".into();
        HttpCompileState {
            prefix,
            context,
            mime_types: HashMap::new(),
            default_type: "text/plain".to_string(),
            log_formats: HashMap::new(),
            upstreams: HashMap::new(),
            cache_paths: HashMap::new(),
            maps: HashMap::new(),
            geos: HashMap::new(),
            split_clients: HashMap::new(),
            limit_req_zones: HashMap::new(),
            limit_conn_zones: HashMap::new(),
            charset_maps: Vec::new(),
            limit_req_directives: Vec::new(),
            limit_conn_directives: Vec::new(),
            server_directives: Vec::new(),
            seen_proxy_redirect: false,
            seen_proxy_cookie_domain: false,
            seen_proxy_cookie_path: false,
            seen_proxy_cookie_flags: false,
            seen_real_ip_from: false,
            seen_ssl_protocols: false,
            seen_proxy_ssl_protocols: false,
            seen_mirror: MirrorSeen::default(),
            seen_addition: AdditionSeen::default(),
            seen_ssi: SsiSeen::default(),
            seen_userid: UserIdSeen::default(),
            seen_secure_link: SecureLinkSeen::default(),
            seen_browser: BrowserSeen::default(),
            seen_expires: false,
            seen_if_modified_since: false,
            access_log_seen: false,
            seen_scope: SeenScopeDirectives::default(),
        }
    }
}
