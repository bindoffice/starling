use super::*;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct NextUpstreamConfig {
    pub(in crate::config::compile) flags: u32,
    pub tries: usize,
    pub timeout: Duration,
}

impl Default for NextUpstreamConfig {
    fn default() -> Self {
        Self {
            flags: NEXT_UPSTREAM_ERROR | NEXT_UPSTREAM_TIMEOUT,
            tries: 0,
            timeout: Duration::ZERO,
        }
    }
}

impl NextUpstreamConfig {
    pub fn retry_error(&self) -> bool {
        self.flags & NEXT_UPSTREAM_ERROR != 0
    }

    pub fn retry_timeout(&self) -> bool {
        self.flags & NEXT_UPSTREAM_TIMEOUT != 0
    }

    pub fn retry_invalid_header(&self) -> bool {
        self.flags & NEXT_UPSTREAM_INVALID_HEADER != 0
    }

    pub fn retry_non_idempotent(&self) -> bool {
        self.flags & NEXT_UPSTREAM_NON_IDEMPOTENT != 0
    }

    pub fn retry_status(&self, status: u16) -> bool {
        let flag = match status {
            403 => NEXT_UPSTREAM_HTTP_403,
            404 => NEXT_UPSTREAM_HTTP_404,
            429 => NEXT_UPSTREAM_HTTP_429,
            500 => NEXT_UPSTREAM_HTTP_500,
            502 => NEXT_UPSTREAM_HTTP_502,
            503 => NEXT_UPSTREAM_HTTP_503,
            504 => NEXT_UPSTREAM_HTTP_504,
            _ => return false,
        };
        self.flags & flag != 0
    }
}

